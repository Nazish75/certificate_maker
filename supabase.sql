-- ==========================================
-- CERTIFICATEMAKER SUPABASE SETUP
-- ==========================================
-- Run this whole file in Supabase SQL Editor.
-- Never put your Supabase Secret key in browser code.

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  recipient text not null,
  achievement text,
  description text,
  date date,
  instructor text,
  organization text,
  template text default 'classic',
  certificate_file_url text,
  saved_at timestamptz default now()
);

alter table public.certificates
add column if not exists date date;

alter table public.certificates
add column if not exists certificate_file_url text;

alter table public.certificates enable row level security;

drop policy if exists "Users can view their own certificates" on public.certificates;
drop policy if exists "Users can insert their own certificates" on public.certificates;
drop policy if exists "Users can update their own certificates" on public.certificates;
drop policy if exists "Users can delete their own certificates" on public.certificates;

create policy "Users can view their own certificates"
on public.certificates
for select
to authenticated
using (auth.uid() = user_id);

create policy "Users can insert their own certificates"
on public.certificates
for insert
to authenticated
with check (auth.uid() = user_id);

create policy "Users can update their own certificates"
on public.certificates
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "Users can delete their own certificates"
on public.certificates
for delete
to authenticated
using (auth.uid() = user_id);


-- ==========================================
-- CERTIFICATE PDF STORAGE
-- ==========================================

insert into storage.buckets (id, name, public)
values ('certificates', 'certificates', true)
on conflict (id) do update set public = true;


-- Authenticated users can upload their own folder:
-- storage path = user_id/certificate_id.pdf
drop policy if exists "Users can upload certificate PDFs" on storage.objects;

create policy "Users can upload certificate PDFs"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'certificates'
  and (storage.foldername(name))[1] = auth.uid()::text
);


-- Authenticated users can update/replace their own PDF.
drop policy if exists "Users can update certificate PDFs" on storage.objects;

create policy "Users can update certificate PDFs"
on storage.objects
for update
to authenticated
using (
  bucket_id = 'certificates'
  and (storage.foldername(name))[1] = auth.uid()::text
)
with check (
  bucket_id = 'certificates'
  and (storage.foldername(name))[1] = auth.uid()::text
);


-- Authenticated users can delete their own PDF.
drop policy if exists "Users can delete certificate PDFs" on storage.objects;

create policy "Users can delete certificate PDFs"
on storage.objects
for delete
to authenticated
using (
  bucket_id = 'certificates'
  and (storage.foldername(name))[1] = auth.uid()::text
);


notify pgrst, 'reload schema';
